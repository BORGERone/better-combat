   public static boolean matchesAnyPattern(String id, List<? extends String> patterns) {
      if (patterns == null || patterns.isEmpty()) {
         return false;
      }
      String normalizedId = id.toLowerCase(Locale.ROOT);
      for (String raw : patterns) {
         if (raw != null && !raw.isBlank() && wildcardMatch(normalizedId, raw.trim().toLowerCase(Locale.ROOT))) {
            return true;
         }
      }
      return false;
   }

   public static boolean wildcardMatch(String text, String pattern) {
      if (!pattern.contains("*")) {
         return text.equals(pattern);
      }
      int ti = 0;
      int pi = 0;
      int starIdx = -1;
      int matchIdx = 0;
      while (ti < text.length()) {
         if (pi < pattern.length() && pattern.charAt(pi) == text.charAt(ti)) {
            pi++;
            ti++;
         } else if (pi < pattern.length() && pattern.charAt(pi) == '*') {
            starIdx = pi++;
            matchIdx = ti;
         } else if (starIdx != -1) {
            pi = starIdx + 1;
            ti = ++matchIdx;
         } else {
            return false;
         }
      }
      while (pi < pattern.length() && pattern.charAt(pi) == '*') {
         pi++;
      }
      return pi == pattern.length();
   }

